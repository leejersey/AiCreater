import React from 'react';

export type IconProps = React.SVGProps<SVGSVGElement> & {
  size?: number | string;
  className?: string;
};

function createIcon(d: string | React.ReactNode, defaultViewBox = '0 0 24 24') {
  return function Icon({size = 16, className = '', ...props}: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox={defaultViewBox}
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
        className={`icon-svg ${className}`.trim()}
        {...props}
      >
        {typeof d === 'string' ? <path d={d} /> : d}
      </svg>
    );
  };
}

