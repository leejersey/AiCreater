// 场景类型到专属图标的映射
export function SceneTypeIcon({type, size = 14, className = ''}: {type: string; size?: number; className?: string}) {
  switch (type) {
    case 'code_walkthrough':
      return <Code size={size} className={className} />;
    case 'flow_diagram':
      return <Workflow size={size} className={className} />;
    case 'comparison_panel':
      return <Columns size={size} className={className} />;
    case 'state_diagram':
      return <Database size={size} className={className} />;
    case 'execution_timeline':
      return <Activity size={size} className={className} />;
    case 'data_chart':
      return <BarChart size={size} className={className} />;
    case 'card_sequence':
      return <Layers size={size} className={className} />;
    case 'title_reveal':
    case 'concept':
    default:
      return <Type size={size} className={className} />;
  }
}
