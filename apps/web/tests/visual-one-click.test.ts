import test from 'node:test';
import assert from 'node:assert/strict';
import {visualCreateVideoAction,visualRenderVideoAction,visualRepairAndRenderAction,visualRepairDesignVideoAction} from '../lib/visual-workbench-actions';
import {type VisualJob} from '../lib/visual-workbench';
test('main generation authorizes a bounded automatic container pipeline once',()=>{
 const action=visualCreateVideoAction('s',1,'source',true,true);
 assert.equal(action.path,'/create-video');
 assert.equal(action.body.max_requests,2);assert.equal(action.body.auto_repair_requests,1);
 assert.equal(action.body.timing_mode,'draft');
 assert.match(String(action.confirmation.message),/受限容器/);
 assert.match(String(action.confirmation.message),/额外最多 1 次/);
 const job:VisualJob={id:'g',project_id:'p',scene_id:'s',kind:'generate',state:'succeeded',result:{sha256:'a'.repeat(64),source:'export {}'}};
 const render=visualRenderVideoAction(job,false);
 assert.equal(render.path,'/g/render-video');
 assert.deepEqual(render.body,{confirmed:true,auto_repair_requests:0});
 assert.ok(!render.confirmation.detail?.includes('SHA-256'));
 const repair=visualRepairAndRenderAction({...job,id:'preview',kind:'preview',result:{sha256:'a'.repeat(64),geometry:{status:'failed'}}});
 assert.equal(repair.body.auto_render,true);assert.equal(repair.body.max_requests,1);
 assert.match(String(repair.confirmation.message),/受限容器/);
 const designRepair=visualRepairDesignVideoAction({...job,id:'design',state:'failed',result:{requests_dispatched:1}});
 assert.equal(designRepair.path,'/design/repair-design-video');
 assert.deepEqual(designRepair.body,{confirmed:true,max_requests:2});
 assert.match(String(designRepair.confirmation.message),/复用这次失败设计/);
});
